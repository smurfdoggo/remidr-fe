import { Platform } from 'react-native';
import tokens from './theme-tokens.json';

// Compatibility aliases for existing themed components, backed by shared tokens.
function componentColors(colors: typeof tokens.light) {
  return {
    ...colors,
    text: colors.foreground,
    backgroundElement: colors.secondary,
    backgroundSelected: colors.accent,
    textSecondary: colors.mutedForeground,
  };
}

export const Colors = {
  light: componentColors(tokens.light),
  dark: componentColors(tokens.dark),
};

export type ThemeColor = keyof typeof Colors.light & keyof typeof Colors.dark;

export const Fonts = Platform.select({
  ios: {
    /** iOS `UIFontDescriptorSystemDesignDefault` */
    sans: 'system-ui',
    /** iOS `UIFontDescriptorSystemDesignSerif` */
    serif: 'ui-serif',
    /** iOS `UIFontDescriptorSystemDesignRounded` */
    rounded: 'ui-rounded',
    /** iOS `UIFontDescriptorSystemDesignMonospaced` */
    mono: 'ui-monospace',
  },
  default: {
    sans: 'normal',
    serif: 'serif',
    rounded: 'normal',
    mono: 'monospace',
  },
  web: {
    sans: 'var(--font-display)',
    serif: 'var(--font-serif)',
    rounded: 'var(--font-rounded)',
    mono: 'var(--font-mono)',
  },
});

